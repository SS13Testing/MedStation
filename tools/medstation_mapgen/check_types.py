#!/usr/bin/env python3
"""Checks that every type path used in the given .dmm files is declared somewhere in the codebase.

Usage: python3 tools/medstation_mapgen/check_types.py _maps/map_files/debug/medstation.dmm [more.dmm ...]
Directional mapping helpers (/directional/north etc.) are generated by macros, so they are accepted by pattern.
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from dmm import Dmm

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DECL = re.compile(r"^\s*(/[A-Za-z0-9_/]+)\s*(?:\{|$|//)")
PROCDEF = re.compile(r"^(/[A-Za-z0-9_/]+?)(?:/proc)?/[A-Za-z0-9_]+\(")
MACRO_SUFFIX = re.compile(r"/(directional|spawner/directional)/(north|south|east|west)$")


def declared_types():
	types = set()
	for base in ("code", "monkestation", "modular_skyrat" if os.path.isdir(os.path.join(ROOT, "modular_skyrat")) else "code"):
		for dirpath, _, files in os.walk(os.path.join(ROOT, base)):
			for f in files:
				if not f.endswith(".dm"):
					continue
				try:
					text = open(os.path.join(dirpath, f), errors="ignore").read()
				except OSError:
					continue
				for line in text.split("\n"):
					m = DECL.match(line)
					pm = PROCDEF.match(line) if not m else None
					if pm:
						m = pm
					if m and ("(" not in line.split("//")[0] or pm):
						path = m.group(1)
						parts = path.strip("/").split("/")
						for i in range(1, len(parts) + 1):
							types.add("/" + "/".join(parts[:i]))
	return types


def main(files):
	known = declared_types()
	bad = {}
	for f in files:
		m = Dmm.load(f)
		for atoms in set(m.tiles.values()):
			for atom in atoms:
				path = atom.split("{")[0].strip()
				if path in known or MACRO_SUFFIX.search(path) or path == "/turf/open/space/basic" or path.startswith("/turf/template_noop") or path.startswith("/area/template_noop"):
					continue
				bad.setdefault(path, set()).add(os.path.basename(f))
	for path, where in sorted(bad.items()):
		print("UNKNOWN %s  (%s)" % (path, ", ".join(sorted(where))))
	print("%d unknown type(s) in %d file(s)" % (len(bad), len(files)))
	return 1 if bad else 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
